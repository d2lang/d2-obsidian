import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";
import { readFileSync } from "node:fs";
import { join } from "node:path";

const sdkDirectory = "node_modules/@d2lang/d2";
const sdk = JSON.parse(readFileSync(join(sdkDirectory, "package.json"), "utf8"));
const notices = [
	join(sdkDirectory, "LICENSE.txt"),
	join(sdkDirectory, "THIRD_PARTY_NOTICES.txt"),
	"node_modules/markdown-it/LICENSE",
	"node_modules/entities/LICENSE",
	"node_modules/linkify-it/LICENSE",
	"node_modules/mdurl/LICENSE",
	"node_modules/punycode.js/LICENSE-MIT.txt",
	"node_modules/uc.micro/LICENSE.txt",
	"node_modules/which/LICENSE",
	"node_modules/isexe/LICENSE",
]
	.map((file) => readFileSync(file, "utf8").replace(/\*\//g, "* /"))
	.join("\n\n");
const banner = `/*!
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin: https://github.com/d2lang/d2-obsidian
D2 compiler: @d2lang/d2@${sdk.version} (${sdk.homepage})
${notices}
*/`;

const prod = process.argv[2] === "production";

esbuild
	.build({
		banner: {
			js: banner,
		},
		entryPoints: ["./src/main.ts"],
		bundle: true,
		external: [
			"obsidian",
			"electron",
			"@codemirror/autocomplete",
			"@codemirror/collab",
			"@codemirror/commands",
			"@codemirror/language",
			"@codemirror/lint",
			"@codemirror/search",
			"@codemirror/state",
			"@codemirror/view",
			"@lezer/common",
			"@lezer/highlight",
			"@lezer/lr",
			...builtins,
		],
		format: "cjs",
		watch: !prod,
		minify: prod,
		target: "es2018",
		logLevel: "info",
		sourcemap: prod ? false : "inline",
		treeShaking: true,
		outfile: "main.js",
	})
	.catch(() => process.exit(1));
